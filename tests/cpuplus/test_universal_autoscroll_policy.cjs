"use strict";
const fs=require("node:fs");
const path=require("node:path");
const assert=require("node:assert/strict");
const vm=require("node:vm");
const source=fs.readFileSync(path.join(__dirname,"../../services/input/UniversalAutoscrollPolicy.js"),"utf8").replace(/^\.pragma library\s*/m,"");
const policy={};
vm.runInNewContext(source,policy);
let state=policy.initial();
assert.equal(state.phase,"idle");
const a=policy.input(state,"middle",400,300,"focused-app-5");
assert.equal(a.ok,true);
state=a.state;
assert.equal(state.phase,"active");
assert.equal(policy.speed(0),0);
assert.equal(policy.speed(15),0);
assert.equal(policy.speed(-15),0);
state=policy.input(state,"move",400,365,"focused-app-5").state;
let a1=policy.tick(state,16,"focused-app-5");
let a2=policy.tick(state,16,"different-target");
assert.equal(a1.ok,true);
assert.ok(a1.y>0);
assert.equal(a1.x,0);
assert.equal(a2.ok,false);
assert.equal(a2.y,0);
state=policy.input(state,"move",400,600,"focused-app-5").state;
assert.ok(policy.tick(state,16,"focused-app-5").y>a1.y);
assert.ok(policy.speed(1000000)<=policy.MAX_PIXELS_PER_SECOND);
assert.equal(policy.tick(state,1000,"focused-app-5").ok,false);
state=policy.input(state,"move",400,200,"focused-app-5").state;
assert.ok(policy.tick(state,16,"focused-app-5").y<0);
const e=policy.input(state,"escape",0,0,"focused-app-5");
assert.equal(e.state.phase,"idle");
assert.equal(policy.tick(e.state,16,"focused-app-5").ok,false);
for(const stopEvent of ["middle","target_lost","device_removed","service_stopped"]){
 const original=policy.begin(policy.initial(),100,100,"app").state;
 assert.equal(policy.input(original,stopEvent,100,100,"app").state.phase,"idle");
}
assert.equal(policy.begin(policy.initial(),NaN,0,"app").ok,false);
assert.equal(policy.begin(policy.initial(),0,0,"").ok,false);
console.log("UNIVERSAL_AUTOSCROLL_ENGINE_PASS // PURE_RATE_ONLY");
