const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const pane = fs.readFileSync(path.join(__dirname, "../widgets/cpuplus/CpuPlusMemoryActuatorPane.qml"), "utf8");
assert.match(pane, /menus: \["CAP", "POL", "PROC", "AUTO", "DIAG", "PROF"\]/);
assert.match(pane, /readonly property int menuIndex: CpuPlusDiagnostics\.memoryMenuIndex/);
assert.match(pane, /onLeftClicked: root.selectMenu\(index\)/);
assert.match(pane, /anchors.top: menuRail.bottom/);
assert.match(pane, /anchors.top: root.page === "CAP" \? capInstrument.bottom : menuRail.bottom/);
assert.match(pane, /visible: root.page !== "CAP" \|\| root.capSection !== 0/);
assert.match(pane, /anchors.bottom: footer.top/);
assert.match(pane, /visible: root.page === "CAP" && root.capSection === 1\s+enabled: visible/);
assert.equal((pane.match(/\bProcess\s*\{/g) || []).length, 1);
assert.equal((pane.match(/\bTimer\s*\{/g) || []).length, 1);
assert.equal((pane.match(/\bCpuPlusMemoryAddControl\s*\{/g) || []).length, 1);
assert.match(pane, /CpuPlusMemoryAddControl\s*\{\s*id: addControl\s*width: parent.width\s*stagedGiB: root.stagedGiB\s*sample: root.sample/);
assert.match(pane, /CpuPlusSwapComposition\s*\{\s*width: parent.width\s*sample: root.sample\s*capacity: root.capacity/);
assert.match(pane, /CpuPlusMemoryCapacitySlider\s*\{/);
const slider = fs.readFileSync(path.join(__dirname, "../widgets/cpuplus/CpuPlusMemoryCapacitySlider.qml"), "utf8");
assert.match(slider, /SelectorSlider\s*\{/);
assert.match(slider, /rotation: 90/);
assert.match(slider, /horizontalStepPresentation: true/);
assert.match(slider, /selectorProfile: "step"/);
assert.match(slider, /valueStep: 4/);
assert.match(slider, /if \(root.enabledSlider\) root.valueRequested\(value\)/);
assert.doesNotMatch(slider, /Controls\.Slider|MouseArea\s*\{/);
assert.match(pane, /onValueRequested: function\(value\) \{ root.stageCapacity\(value\); \}/);
assert.match(pane, /SelectorDial\s*\{/);
assert.match(pane, /active: root.page === "POL"/);
assert.match(pane, /onValueRequested: function\(value\) \{ root.stagePolicy\(Math.round\(value\)\); \}/);
assert.match(pane, /PREVIEW ONLY \/\/ APPLY NOT CONNECTED/);
assert.match(pane, /RAM bright = estimated available/);
assert.match(pane, /root.sample.available \/ root.sample.total/);
const vm = require("node:vm");
const actions = pane.slice(pane.indexOf("    function stageCapacity"), pane.indexOf("    onSampleChanged"));
const ctx = vm.createContext({page:"CAP",capSection:0,capacity:{},sample:{swappiness:60},MemoryOperation:{busy:false},stagedGiB:16,stagedSwappiness:60});
vm.runInContext(actions,ctx);
ctx.stageCapacity(24); assert.equal(ctx.stagedGiB,24);
ctx.capSection=1; ctx.stageCapacity(32); assert.equal(ctx.stagedGiB,24); ctx.capSection=0;
for (const v of [-4,65,17,NaN,"32"]) ctx.stageCapacity(v);
assert.equal(ctx.stagedGiB,24);
ctx.MemoryOperation.busy=true; ctx.stageCapacity(32); assert.equal(ctx.stagedGiB,24);
ctx.MemoryOperation.busy=false; ctx.page="POL"; ctx.stageCapacity(32); assert.equal(ctx.stagedGiB,24);
ctx.stagePolicy(150); assert.equal(ctx.stagedSwappiness,150);
for (const v of [-1,201,3.5,NaN,"100"]) ctx.stagePolicy(v);
assert.equal(ctx.stagedSwappiness,150);
ctx.sample=null; ctx.stagePolicy(100); assert.equal(ctx.stagedSwappiness,150);
ctx.sample={swappiness:40}; ctx.MemoryOperation.busy=true; ctx.stagePolicy(100); assert.equal(ctx.stagedSwappiness,150);
ctx.MemoryOperation.busy=false; ctx.page="CAP"; ctx.stagePolicy(100); assert.equal(ctx.stagedSwappiness,150);
ctx.capacity=null; ctx.stageCapacity(32); assert.equal(ctx.stagedGiB,24);
assert.match(pane, /QUEUE \/\/ NOT CONNECTED/);
assert.doesNotMatch(pane, /MemoryOperation\.request\(/);
const fn = pane.slice(pane.indexOf("function selectMenu"), pane.indexOf("    Grid {"));
assert.match(fn, /if \(index < 0 \|\| index >= menus.length \|\| index === menuIndex\) return;/);
for (const field of ["armed", "persistArmed", "expandArmed"]) assert.ok(pane.includes("addControl." + field + " = false;"));
assert.match(fn, /clearCapConfirmation\(\);/);
assert.match(pane, /function selectCapSection[\s\S]*?clearCapConfirmation\(\);/);
assert.match(fn, /CpuPlusDiagnostics\.memoryMenuIndex = index;\s*scroll.contentY = 0;/);
assert.doesNotMatch(fn, /stagedGiB\s*=|refresh\(|running\s*=|MemoryOperation\.\w/);
console.log("CPU++ memory navigation source contract PASS (not a native QML test)");
