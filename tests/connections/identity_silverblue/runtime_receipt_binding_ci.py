#!/usr/bin/env python3
"""C4b: guest-local signed release ↔ installed runtime receipt-key diagnostic.

A disposable official Silverblue guest creates a *new* test-only release
signature over its observed installed RPM/source and actual runtime public
receipt key. The same public key must verify the four real gateway denials.
No private key is exported, shipped in RPM, logged, or uploaded.

The release root is minted IN THE GUEST, therefore this is NOT independently
enrolled authority or remotely authenticated kernel/process evidence. Every
authentication / production / C5 / sign-in grant stays hard false.
"""
from __future__ import annotations

import hashlib
import hmac
import importlib.util
import os
from pathlib import Path
import stat
import sys

from cryptography.hazmat.primitives.asymmetric.ed25519 import (
    Ed25519PrivateKey, Ed25519PublicKey,
)
from cryptography.hazmat.primitives.serialization import (
    Encoding, PublicFormat,
)

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "services/identity/silverblue_release_candidate_v1.py"
if not SOURCE.exists():
    SOURCE = Path("/usr/local/libexec/postapollo-id-ci-release-candidate.py")
_spec = importlib.util.spec_from_file_location("c4b_ci_release_candidate", SOURCE)
if _spec is None or _spec.loader is None:
    raise RuntimeError("C4B_BINDING_IDENTITY_RELEASE_VERIFIER_MISSING")
I = importlib.util.module_from_spec(_spec)
sys.modules[_spec.name] = I
_spec.loader.exec_module(I)

SCHEMA = "postapollo.identity.c4b.runtime-receipt-binding.guest-local-ci-v1"
MAX_RPM = 8 * 1024 * 1024
MAX_FILE = 2 * 1024 * 1024
DENIED = {
    "operatorEnrollmentRootCustodyVerified": False,
    "independentlySignedRemoteHostWitnessVerified": False,
    "installedHostAuthenticated": False,
    "externalChallengeIssuerVerified": False,
    "externalRollbackResistanceVerified": False,
    "c5HumanConsentVerified": False,
    "hostAuthenticated": False,
    "canBeginSignIn": False,
    "credentialActionsEnabled": False,
    "productionAuthority": False,
}

class Refused(ValueError):
    """A CI release, installed source, or receipt signer was not bound."""

def _deny(code):
    raise Refused(code)

def _digest_file(path: Path, *, ceiling: int, mode: int):
    # Only caller-allowlisted absolute paths. Immutable guest /usr may be
    # hardlinked into OSTree objects; do not forbid a legitimate nlink > 1.
    if not isinstance(path, Path) or not path.is_absolute():
        _deny("C4B_BINDING_NONABSOLUTE_SOURCE_PATH")
    fd = None
    try:
        fd = os.open(str(path), os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC)
        before = os.fstat(fd)
        if (not stat.S_ISREG(before.st_mode) or
                before.st_uid != 0 or before.st_gid != 0 or
                stat.S_IMODE(before.st_mode) != mode or
                not 0 < before.st_size <= ceiling):
            _deny("C4B_BINDING_UNSAFE_SOURCE_OR_MODE")
        digest = hashlib.sha256()
        size = 0
        while True:
            block = os.read(fd, min(65536, ceiling + 1 - size))
            if not block:
                break
            size += len(block)
            if size > ceiling:
                _deny("C4B_BINDING_OVERSIZE_SOURCE")
            digest.update(block)
        after = os.fstat(fd)
        if (size != before.st_size or
                (before.st_dev, before.st_ino, before.st_size,
                 before.st_mtime_ns, before.st_ctime_ns) !=
                (after.st_dev, after.st_ino, after.st_size,
                 after.st_mtime_ns, after.st_ctime_ns)):
            _deny("C4B_BINDING_SOURCE_CHANGED_DURING_READ")
        return digest.hexdigest()
    except OSError as exc:
        raise Refused("C4B_BINDING_SOURCE_UNREADABLE") from exc
    finally:
        if fd is not None:
            os.close(fd)

def verify_runtime_binding_ci_only(
    *, signed_release: bytes, release_signature: bytes,
    independently_pinned_release_root: Ed25519PublicKey,
    release_receipt_public: bytes, actual_runtime_receipt_public: bytes,
    rpm_sha256: str, installed_file_sha256: dict,
    minimum_epoch: int, minimum_sequence: int,
    verified_actions: tuple,
):
    """A *signed* release must name the SAME signer as the actual receipts.

    This function cannot prove the caller's pins are independently trusted.
    In the guest integration, the root and release are generated by the guest
    supervisor, and receipt verification happens on the actual native socket.
    """
    if (type(release_receipt_public) is not bytes or
            type(actual_runtime_receipt_public) is not bytes or
            len(release_receipt_public) != 32 or
            len(actual_runtime_receipt_public) != 32 or
            type(installed_file_sha256) is not dict or
            type(verified_actions) is not tuple or
            verified_actions != ("BEGIN", "STATUS", "CANCEL", "RECOVER")):
        _deny("C4B_BINDING_EXACT_KEYS_FOUR_DENIALS_AND_ROSTER_REQUIRED")
    if not hmac.compare_digest(
        release_receipt_public, actual_runtime_receipt_public,
    ):
        _deny("C4B_BINDING_SIGNED_RELEASE_KEY_NOT_RUNTIME_SIGNER")
    if not isinstance(independently_pinned_release_root, Ed25519PublicKey):
        _deny("C4B_BINDING_SEPARATE_RELEASE_ROOT_REQUIRED")
    root_raw = independently_pinned_release_root.public_bytes(
        Encoding.Raw, PublicFormat.Raw,
    )
    if hmac.compare_digest(root_raw, release_receipt_public):
        _deny("C4B_BINDING_RELEASE_ROOT_MUST_DIFFER_FROM_RECEIPT_SIGNER")
    try:
        candidate = I.assess_synthetic_release(
            signed_release=signed_release,
            signature=release_signature,
            independently_pinned_root=independently_pinned_release_root,
            independently_pinned_receipt_key=release_receipt_public,
            independently_measured_rpm_sha256=rpm_sha256,
            independently_measured_files=installed_file_sha256,
            minimum_epoch=minimum_epoch,
            minimum_sequence=minimum_sequence,
        )
    except I.CandidateRefused as exc:
        raise Refused("C4B_BINDING_SIGNED_SOURCE_OR_ENROLLMENT_REFUSED") from exc
    if any((
        candidate.installed_guest_measured,
        candidate.host_authenticated,
        candidate.production_authority,
        candidate.can_begin_sign_in,
        candidate.credential_actions_enabled,
    )):
        _deny("C4B_BINDING_CANDIDATE_ATTEMPTED_AUTHORITY_PROMOTION")
    return {
        "schema": SCHEMA,
        "fourActualNativeDenialActionsSignedBySameRuntimeKeyInGuestCI": True,
        "guestLocalSignedReleaseContainsRuntimeReceiptKeyInCI": True,
        "guestGeneratedReleaseRootIndependentOfProduction": True,
        "rpmSha256": rpm_sha256,
        "releaseEpoch": candidate.epoch,
        "releaseSequence": candidate.sequence,
        **DENIED,
    }

def rehearse_guest_local_ci_only(
    *, actual_runtime_receipt_public: bytes,
    verified_actions: tuple,
    signed_rpm_archive: Path,
):
    """Run only from the existing root probe INSIDE real disposable C4b VM.

    Generate an isolated in-memory CI release root AFTER the guest runtime
    key exists; compare actual runtime signer to the freshly signed release.
    This proves test wiring, NOT independent remote root custody.
    """
    if (sys.platform != "linux" or os.geteuid() != 0 or
            os.environ.get("POST_APOLLO_C4B_TEST_GUEST") != "1" or
            os.environ.get("GITHUB_ACTIONS") != "true" or
            not Path("/run/ostree-booted").exists()):
        _deny("C4B_BINDING_OFFICIAL_GUEST_CI_SCOPE_REQUIRED")
    try:
        if Path("/sys/fs/selinux/enforce").read_bytes().strip() != b"1":
            _deny("C4B_BINDING_ENFORCING_SELINUX_REQUIRED")
    except OSError as exc:
        raise Refused("C4B_BINDING_SELINUX_OBSERVATION_UNAVAILABLE") from exc
    if (not isinstance(signed_rpm_archive, Path) or
            signed_rpm_archive != Path(
                "/var/lib/postapollo-id-ci-assets/identity-silverblue-ci.rpm"
            )):
        _deny("C4B_BINDING_UNTRUSTED_RPM_ARCHIVE_PATH")
    # C4b parent already verifies signed RPM in an isolated rpmdb and rpm -V
    # against the installed OSTree deployment before invoking this helper.
    rpm_sha = _digest_file(signed_rpm_archive, ceiling=MAX_RPM, mode=0o600)
    installed = {
        path: _digest_file(
            Path(path), ceiling=MAX_FILE,
            mode=0o644 if path == I.UNIT_PATH else 0o555,
        )
        for path in sorted(I.FILES)
    }
    if type(actual_runtime_receipt_public) is not bytes or len(
        actual_runtime_receipt_public
    ) != 32:
        _deny("C4B_BINDING_ACTUAL_PUBLIC_KEY_INVALID")
    ephemeral_guest_root = Ed25519PrivateKey.generate()
    document = {
        "schema": I.SCHEMA,
        "role": I.ROLE,
        "package": I.PACKAGE,
        "unit": I.UNIT,
        "epoch": 1,
        "sequence": 1,
        "rpmSha256": rpm_sha,
        "receiptKeySha256": hashlib.sha256(
            actual_runtime_receipt_public,
        ).hexdigest(),
        "files": installed,
    }
    raw = I._canonical(document)
    signature = ephemeral_guest_root.sign(I.DOMAIN + raw)
    kwargs = dict(
        signed_release=raw,
        release_signature=signature,
        independently_pinned_release_root=ephemeral_guest_root.public_key(),
        release_receipt_public=actual_runtime_receipt_public,
        actual_runtime_receipt_public=actual_runtime_receipt_public,
        rpm_sha256=rpm_sha,
        installed_file_sha256=installed,
        minimum_epoch=1,
        minimum_sequence=1,
        verified_actions=verified_actions,
    )
    result = verify_runtime_binding_ci_only(**kwargs)
    # A different *release* fixture / controller public key must never be
    # accepted as the signer of the real guest's four UNAVAILABLE receipts.
    mismatched_public = Ed25519PrivateKey.generate().public_key().public_bytes(
        Encoding.Raw, PublicFormat.Raw,
    )
    if mismatched_public == actual_runtime_receipt_public:
        _deny("C4B_BINDING_TEST_KEY_COLLISION")
    try:
        verify_runtime_binding_ci_only(
            **{**kwargs, "release_receipt_public": mismatched_public},
        )
    except Refused:
        pass
    else:
        _deny("C4B_BINDING_NEGATIVE_SUBSTITUTION_DID_NOT_REFUSE")
    return result
