const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const root = path.join(__dirname,"../..","widgets/cpuplus");
const ctx = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(root,"CpuPlusAdvancedPolicy.js"),"utf8"),ctx);
const good = "100\n10\n0\n20\n0\n500\n3000\n";
let p=ctx.parse(good);
assert.equal(p.cachePressure,100);
assert.equal(p.background.mode,"RATIO");
assert.equal(p.writer.mode,"RATIO");
assert.equal(ctx.pairLabel(p.writer),"20%");
assert.equal(ctx.seconds(p.writebackCentisecs),"5.00 s");
assert.equal(ctx.seconds(p.expireCentisecs),"30.00 s");
p=ctx.parse("200\n0\n1048576\n0\n2097152\n0\n100\n");
assert.equal(p.background.mode,"BYTES");
assert.equal(ctx.pairLabel(p.writer),"2097152 B");
assert.equal(p.writebackCentisecs,0);
p=ctx.parse("0\n10\n100\n0\n0\n1\n1\n");
assert.equal(p.background.mode,"INCONSISTENT");
assert.equal(p.writer.mode,"BOTH ZERO");
for(const raw of [null,"",good+"1\n",good.replace("20\n","101\n"),good.replace("100","-1"),good.replace("100","9999999999999999"),good.replace("100","1e2"),good.replace("100\n",""),good.replace("500","NaN")]) assert.equal(ctx.parse(raw),null);
assert.equal(ctx.paths().length,7);
assert.ok(ctx.paths().every(p=>/^\/proc\/sys\/vm\/[a-z_]+$/.test(p)));
const qml=fs.readFileSync(path.join(root,"CpuPlusAdvancedPolicyPane.qml"),"utf8");
assert.match(qml,/command: \["\/usr\/bin\/cat"\]\.concat\(Policy.paths\(\)\)/);
assert.equal((qml.match(/\bProcess\s*\{/g)||[]).length,1);
assert.doesNotMatch(qml,/\b(?:Timer|FileView|pkexec|sudo|execDetached|MemoryOperation)\b/);
assert.doesNotMatch(qml,/Component\.onCompleted|running:\s*true/);
assert.match(qml,/observation = exitOk \? Policy.parse\(raw\) : null/);
const observed=ctx.parse(good);
const ratio=ctx.previewSpec(observed,"background");
assert.equal(ratio.value,10);
assert.equal(ratio.unit,"%");
assert.equal(ctx.validPreview(ratio,101),false);
assert.equal(ctx.validPreview(ratio,0),false);
assert.equal(ctx.validPreview(ratio,15),true);
assert.equal(ctx.validPreview(ratio,"15"),false);
assert.equal(ctx.pairWarning(observed,"background",20),"CAUTION // BACKGROUND AT OR ABOVE WRITER");
assert.equal(ctx.pairWarning(observed,"background",15),"");
const mixed=ctx.parse("100\n10\n0\n0\n2097152\n0\n3000\n");
assert.equal(ctx.previewSpec(mixed,"writer").unit,"B");
assert.equal(ctx.pairWarning(mixed,"writer",1048576),"THRESHOLD ORDER // NOT COMPARABLE");
assert.equal(ctx.previewSpec(ctx.parse("0\n10\n100\n0\n0\n1\n1\n"),"background"),null);
assert.equal(ctx.previewSpec(observed,"arbitrary"),null);
assert.equal(ctx.previewLabel(ctx.previewSpec(observed,"writebackCentisecs"),600),"6.00 s");
assert.match(qml,/if \(!canStage \|\| !Policy.validPreview\(selectedSpec,value\)\) return;/);
console.log("CPU++ advanced VM policy read-only contract PASS");
