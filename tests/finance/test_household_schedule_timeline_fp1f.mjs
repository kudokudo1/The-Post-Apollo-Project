#!/usr/bin/env node
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import vm from "node:vm";
const src=readFileSync(new URL("../../widgets/FinanceHouseholdTimelinePolicy.js",import.meta.url),"utf8");
const p=vm.runInNewContext(src+"\n({project,coverage})");
const id=x=>"p-"+x.repeat(32);
const income={id:id("a"),kind:"income",title:"Income",targetCents:0,savedCents:0,monthlyCents:300000,deadlineMonth:""};
const rent={id:id("b"),kind:"expense",title:"Rent",targetCents:0,savedCents:0,monthlyCents:120000,deadlineMonth:""};
const phone={id:id("c"),kind:"expense",title:"Phone",targetCents:0,savedCents:0,monthlyCents:5000,deadlineMonth:""};
const goal={id:id("d"),kind:"goal",title:"Computer",targetCents:30000,savedCents:10000,monthlyCents:5000,deadlineMonth:"2027-01"};
const bill={id:id("e"),kind:"bill_due",title:"",expenseId:rent.id,dueDay:31,date:"",amountCents:0,fundingGoalId:""};
const skip={id:id("f"),kind:"bill_skip",title:"",expenseId:rent.id,dueDay:0,date:"2026-12",amountCents:0,fundingGoalId:""};
const rows=[income,rent,phone,goal],schedules=[bill,skip],before=JSON.stringify({rows,schedules});
const c=p.coverage(rows,schedules);
assert.equal(c.ok,true);
assert.equal(c.allObligationsKnown,false);
assert.equal(c.dueDateCoverageOnly,true);
assert.equal(c.monthlyExpenseCount,2);
assert.equal(c.datedExpenseCount,1);
assert.equal(c.undatedExpenseCount,1);
assert.equal(c.undatedExpenseTitles[0],"Phone");
assert.equal(c.manualIncomeCount,1);
assert.equal(c.monthlyExceptionCount,1);
const t=p.project(rows,schedules,"2026-11",6,"mine");
assert.equal(t.ok,true);
assert.equal(t.months[0].expenseCents,125000);
assert.equal(t.months[0].billEvents[0].dueDate,"2026-11-30");
assert.equal(t.months[0].changeCents,170000);
assert.equal(t.months[1].expenseCents,5000);
assert.equal(t.months[1].baseExpenseCents,125000);
assert.equal(t.months[1].exceptionEvents.length,1);
assert.equal(t.months[1].exceptionEvents[0].excludedCents,120000);
assert.equal(t.months[1].billEvents.length,0);
assert.equal(t.months[1].changeCents,290000);
assert.equal(t.months[2].expenseCents,125000);
assert.equal(t.months[2].billEvents[0].dueDate,"2027-01-31");
assert.equal(t.months[2].exceptionEvents.length,0);
assert.equal(JSON.stringify({rows,schedules}),before);
assert.equal(p.project(rows,[bill,skip,{...skip,id:id("9")}],
    "2026-11",6,"mine").reason,"DUPLICATE_BILL_EXCEPTION");
assert.equal(p.coverage(rows,[skip]).reason,"SCHEDULE_REFERENCE_MISSING");
assert.equal(p.project(rows,[skip],"2026-11",6,"mine").reason,"SCHEDULE_REFERENCE_MISSING");
assert.equal(p.coverage(rows,[{...skip,date:"2026-13"}]).reason,"INVALID_LOCAL_SCHEDULES");
assert.equal(p.coverage([rent],[]).manualIncomeCount,0);
assert.equal(p.project([rent],[],"2026-11",6,"mine").reason,"ADD_MANUAL_MONTHLY_INCOME");
assert.equal(p.project(rows,[],"2026-11",6,"mine").coverage.undatedExpenseCount,2);
console.log("FinanceW FP1f coverage and one-month exclusion: PASS");
