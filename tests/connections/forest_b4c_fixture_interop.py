#!/usr/bin/env python3
"""TEST-ONLY Forest B4c adapter between #2171 signed-role and #2168 fence fixtures.

This file is deliberately under tests/. It does not issue grants, register a
signing root, install a daemon, read user data, authenticate a human/seat, or
enable Forest. Both fixture public keys may be generated by the same attacker.
A matching signature demonstrates only consistency of untrusted test bytes.
"""
from __future__ import annotations

import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def _load_exact(name, relative):
    spec = importlib.util.spec_from_file_location(name, ROOT / relative)
    if spec is None or spec.loader is None:
        raise RuntimeError("FOREST_B4C_TEST_SOURCE_MISSING")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


SIGNED = _load_exact(
    "forest_c5_unenrolled_fixture_source",
    "services/connections/forest/ForestC5SignedEvidencePreflight.py",
)
FENCE = _load_exact(
    "forest_c5_two_store_untrusted_reference",
    "tests/connections/test_connections_forest_b4c_fence_reference.py",
)

FIXTURE_ONLY = True
PRODUCTION_AUTHORITY = False


def fixture_intent_from_signed_bytes_only(
    intent_wire, requester_record, requester_signature, requester_public,
    reviewer_record, reviewer_signature, reviewer_public, *, now_ms,
):
    """Return a legacy fixture intent and hard-denied signed-role diagnostic.

    This is not a bridge an installed Forest or protected C5 process may use.
    The only output consumed by the legacy fence is disposable test data.
    """
    diagnostic = SIGNED.verify_unenrolled_role_consistency(
        intent_wire, requester_record, requester_signature, requester_public,
        reviewer_record, reviewer_signature, reviewer_public, now_ms=now_ms,
    )
    if any(diagnostic[k] is not False for k in SIGNED.NO_AUTHORITY):
        raise AssertionError("TEST_SOURCE_UNEXPECTEDLY_GRANTED_NATIVE_AUTHORITY")
    if diagnostic["safeActions"]:
        raise AssertionError("TEST_SOURCE_UNEXPECTED_ACTIONS")
    if (SIGNED.AUDIENCE != FENCE.AUDIENCE
            or SIGNED.MODEL.pattern != FENCE.MODEL_SYNTAX.pattern
            or SIGNED.MODEL.flags != FENCE.MODEL_SYNTAX.flags):
        raise AssertionError("FOREST_B4C_MODEL_OR_AUDIENCE_CONTRACT_DRIFT")

    # The signed role verifier has already checked strict canonical bytes,
    # exact signed intent SHA, scope, phase, key fingerprints, nonce and epoch.
    # Reparse the exact SAME unmodified bytes to build a test-only legacy row.
    record, digest = SIGNED._intent(intent_wire, now_ms)
    if digest != diagnostic["intentSha256ObservedUntrusted"]:
        raise AssertionError("SIGNED_INTENT_DIGEST_DRIFT")
    legacy_fixture = {
        "audience": record["audience"],
        "action": record["action"],
        "principal": record["principal"],
        "tree": record["tree"],
        "userTurn": record["userTurn"],
        "attempt": record["attempt"],
        "request": record["request"],
        "grant": record["grant"],
        "model": record["model"],
        "revision": record["revision"],
        "epoch": record["consentEpoch"],
        # Both fixture clocks use milliseconds; no seconds/ms conversion.
        "expiresAt": record["expiresAtMs"],
        # Legacy-only field binds all extra requester/seat/release values
        # through the exact full signed-intent SHA. This is still UNTRUSTED.
        "issuerWitness": digest,
    }
    FENCE._canonical_intent(legacy_fixture)
    return legacy_fixture, diagnostic
