const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const read = p => fs.readFileSync(path.join(__dirname, "../..", p), "utf8");
const view = read("widgets/appcontrol/SystemMonitorView.qml");
const cpu = read("widgets/CpuPlusW.qml");
assert.match(view, /property bool pinnedInstrument: false/);
assert.match(view, /id: fixedInstrument[\s\S]*?UTILIZATION[\s\S]*?SYSTEM STATE[\s\S]*?SYSTEM CONTROL[\s\S]*?PROCESS \/ APP CONTRIBUTORS[\s\S]*?id: contributorScroll/);
assert.match(view, /height: systemMonitorBody.pinnedInstrument\s*\? Math.max\(0, systemMonitorBody.height - fixedInstrument.height - systemMonitorBody.spacing\)/);
assert.match(view, /interactive: systemMonitorBody.pinnedInstrument && contentHeight > height/);
assert.match(view, /onContributorSourceIdChanged: resetContributorScroll\(\)/);
assert.match(view, /controller.runSystemComponentAction\(\s*systemMonitorBody.currentComponent,\s*modelData.action/);
assert.match(view, /controller.terminateSystemContributor\(\s*modelData/);
assert.doesNotMatch(view, /\b(?:Process|Timer|execDetached|pkexec|sudo)\b\s*\{/);
assert.equal((cpu.match(/SystemMonitorView\s*\{/g)||[]).length,1);
assert.match(cpu, /SystemMonitorView\s*\{\s*id: systemMonitorBody\s*pinnedInstrument: true[\s\S]*?anchors.top: selectedMonitorIdentity.bottom/);
const scrollBlock = cpu.split("id: sharedInstrumentScroll")[1].split("anchors.left: parent.left")[0];
assert.match(scrollBlock, /visible: !\(cpuPlusWindow.selectedModeIndex === 6/);
assert.match(scrollBlock, /&& cpuPlusWindow.selectedModeIndex !== 3/);
for (const sub of ["TIME", "CONNECTIONS", "LOCATION"]) assert.ok(scrollBlock.includes('settingsSubMode === "' + sub + '"'));
assert.match(cpu, /height: visible \? \(showingSystem \? 74 : 122\) : 0/);
assert.match(view, /compactMemoryReading: pinnedInstrument && categoryName === "MEMORY"/);
assert.match(view, /id: combinedMemory[\s\S]*?id: availableMemory[\s\S]*?safeComponent.detail[\s\S]*?id: memoryDivider[\s\S]*?text: " \/\/ "[\s\S]*?id: usedMemory[\s\S]*?safeComponent.secondary/);
assert.equal((view.match(/visible: !systemMonitorBody.compactMemoryReading/g)||[]).length,2);
console.log("CPU++ fixed system instruments / contributor scroll source PASS");
